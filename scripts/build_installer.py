#!/usr/bin/env python3
"""Build a standalone installer, requiring no clone or follow-up repository fetch."""
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FILES=['bootstrap.sh','scripts/configure.py','config/AGENTS.md','doctor.sh','scripts/doctor.py']

def build():
    lines=['#!/usr/bin/env bash', '# Generated by scripts/build_installer.py; edit source files instead.',
           'set -euo pipefail',
           'bundle_dir=$(mktemp -d "${TMPDIR:-/tmp}/jayson-dev-bundle.XXXXXXXX")',
           'trap \'rm -rf -- "$bundle_dir"\' EXIT',
           'mkdir -p "$bundle_dir/scripts" "$bundle_dir/config"']
    for name in FILES:
        content=(ROOT/name).read_text()
        delimiter='DEV_BUNDLE_'+hashlib.sha256(content.encode()).hexdigest()[:24]
        assert delimiter not in content.splitlines()
        lines.append(f'cat > "$bundle_dir/{name}" <<\'{delimiter}\'\n'+content.rstrip('\n')+'\n'+delimiter)
    lines.append('bash "$bundle_dir/bootstrap.sh" "$@"')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    target=ROOT/'install.sh'
    target.write_text(build())
    target.chmod(0o755)
    print(target)
